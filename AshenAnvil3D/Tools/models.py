def weapon_bow():
    m = Mesh(["Metal", "Grip"])
    pts = []
    for i in range(9):
        y = -0.55 + 1.1 * i / 8
        z = 0.18 * (1 - (y / 0.55) ** 2)
        pts.append((0, y, z))
    for a, b in zip(pts, pts[1:]):
        cx, cy, cz = ((a[k] + b[k]) / 2 for k in range(3))
        length = math.dist(a, b)
        tilt = math.degrees(math.atan2(b[2] - a[2], b[1] - a[1]))
        m.cylinder("Grip", (cx, cy, cz), 0.025, length + 0.02, 6, rot=(tilt, 0, 0))
    m.box("Metal", (0, 0, 0.0), (0.008, 1.1, 0.008))
    m.box("Grip", (0, 0, 0.18), (0.06, 0.16, 0.06))
    return m


