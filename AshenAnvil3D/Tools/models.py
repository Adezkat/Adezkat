"""Procedural low-poly OBJ model generator for Ashen Anvil 3D.

Every model is flat shaded and split into material groups (usemtl) so Unity imports one
mesh with one sub-mesh per material. Units are metres, +Y is up, models face +Z.
"""
import math
import random


def rot_matrix(rx, ry, rz):
    rx, ry, rz = (math.radians(a) for a in (rx, ry, rz))
    cx, sx, cy, sy, cz, sz = math.cos(rx), math.sin(rx), math.cos(ry), math.sin(ry), math.cos(rz), math.sin(rz)
    # Unity order: Z, then X, then Y  =>  R = Ry * Rx * Rz
    Rz = [[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]
    Rx = [[1, 0, 0], [0, cx, -sx], [0, sx, cx]]
    Ry = [[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]

    def mul(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    return mul(Ry, mul(Rx, Rz))


def apply(m, v):
    return tuple(sum(m[i][k] * v[k] for k in range(3)) for i in range(3))


class Mesh:
    def __init__(self, materials):
        self.materials = materials
        self.faces = {m: [] for m in materials}  # material -> list of [v0, v1, v2, ...] (CCW, outward)

    def add_poly(self, mat, pts):
        self.faces[mat].append([tuple(p) for p in pts])

    def _xf(self, pts, center, rot):
        m = rot_matrix(*rot)
        return [tuple(a + b for a, b in zip(apply(m, p), center)) for p in pts]

    def box(self, mat, center, size, rot=(0, 0, 0)):
        hx, hy, hz = (s / 2 for s in size)
        c = [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, hy, -hz), (-hx, hy, -hz),
             (-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)]
        c = self._xf(c, center, rot)
        for f in [(4, 5, 6, 7), (1, 0, 3, 2), (0, 4, 7, 3), (5, 1, 2, 6), (7, 6, 2, 3), (0, 1, 5, 4)]:
            self.add_poly(mat, [c[i] for i in f])

    def frustum(self, mat, center, r_bottom, r_top, height, segments=8, rot=(0, 0, 0), caps=True, phase=0.0):
        bottom, top = [], []
        for i in range(segments):
            a = phase + 2 * math.pi * i / segments
            bottom.append((math.sin(a) * r_bottom, -height / 2, math.cos(a) * r_bottom))
            top.append((math.sin(a) * r_top, height / 2, math.cos(a) * r_top))
        bottom = self._xf(bottom, center, rot)
        top = self._xf(top, center, rot)
        for i in range(segments):
            j = (i + 1) % segments
            if r_top > 1e-4:
                self.add_poly(mat, [bottom[i], bottom[j], top[j], top[i]])
            else:
                self.add_poly(mat, [bottom[i], bottom[j], top[i]])
        if caps:
            self.add_poly(mat, list(reversed(bottom)))
            if r_top > 1e-4:
                self.add_poly(mat, top)

    def cylinder(self, mat, center, r, h, segments=8, rot=(0, 0, 0)):
        self.frustum(mat, center, r, r, h, segments, rot)

    def cone(self, mat, center, r, h, segments=8, rot=(0, 0, 0)):
        self.frustum(mat, center, r, 0.0, h, segments, rot)

    def sphere(self, mat, center, radius, lon=8, lat=6, scale=(1, 1, 1), jitter=0.0, seed=0, rot=(0, 0, 0)):
        rng = random.Random(seed)
        rings = []
        for j in range(lat + 1):
            theta = math.pi * j / lat
            ring = []
            for i in range(lon):
                phi = 2 * math.pi * i / lon
                k = 1.0 + (rng.uniform(-jitter, jitter) if 0 < j < lat else 0)
                ring.append((math.sin(theta) * math.cos(phi) * radius * scale[0] * k,
                             math.cos(theta) * radius * scale[1] * k,
                             math.sin(theta) * math.sin(phi) * radius * scale[2] * k))
            rings.append(self._xf(ring, center, rot))
        for j in range(lat):
            for i in range(lon):
                n = (i + 1) % lon
                a, b, c, d = rings[j][i], rings[j][n], rings[j + 1][n], rings[j + 1][i]
                if j == 0:
                    self.add_poly(mat, [a, c, d])
                elif j == lat - 1:
                    self.add_poly(mat, [a, b, c])
                else:
                    self.add_poly(mat, [a, b, c, d])

    def write(self, path, name):
        verts, normals, lines = [], [], []
        lines.append(f"# Ashen Anvil 3D - {name} (generated by Tools/generate_unity_assets.py)")
        lines.append(f"o {name}")
        out_faces = []
        for mat in self.materials:
            group = []
            for poly in self.faces[mat]:
                n = normal(poly)
                if n is None:
                    continue
                normals.append(n)
                ni = len(normals)
                idx = []
                for p in poly:
                    verts.append(p)
                    idx.append(len(verts))
                group.append((idx, ni))
            out_faces.append((mat, group))
        for v in verts:
            lines.append("v %.4f %.4f %.4f" % v)
        for n in normals:
            lines.append("vn %.4f %.4f %.4f" % n)
        for mat, group in out_faces:
            if not group:
                continue
            lines.append(f"usemtl {mat}")
            for idx, ni in group:
                lines.append("f " + " ".join(f"{i}//{ni}" for i in idx))
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")
        return len(verts)


def normal(poly):
    # Newell's method
    nx = ny = nz = 0.0
    for i, p in enumerate(poly):
        q = poly[(i + 1) % len(poly)]
        nx += (p[1] - q[1]) * (p[2] + q[2])
        ny += (p[2] - q[2]) * (p[0] + q[0])
        nz += (p[0] - q[0]) * (p[1] + q[1])
    l = math.sqrt(nx * nx + ny * ny + nz * nz)
    if l < 1e-9:
        return None
    return (nx / l, ny / l, nz / l)


