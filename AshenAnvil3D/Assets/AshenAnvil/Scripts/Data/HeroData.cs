using UnityEngine;

namespace AshenAnvil
{
    [CreateAssetMenu(menuName = "Ashen Anvil/Hero", fileName = "Hero_")]
    public class HeroData : ScriptableObject
    {
        [Header("Identity")]
        public string id;
        public string displayName;
        public string title;
        public HeroClass heroClass;
        public Rarity rarity;
        [TextArea(3, 6)] public string lore;
        public int unlockCost = 0;

        [Header("Stats")]
        public StatBlock baseStats = new StatBlock();
        [Tooltip("Added once per level above 1.")]
        public StatBlock growthPerLevel = StatBlock.Zero();

        [Header("Kit")]
        public WeaponData startingWeapon;
        public SkillData skill;

        [Header("Visuals")]
        public CharacterLook look = new CharacterLook();
        [Tooltip("Model prefab (rig + Animator). Generated by Ashen Anvil > Rebuild Project Assets.")]
        public GameObject prefab;

        public bool IsRanged => heroClass == HeroClass.Archer || heroClass == HeroClass.Mage;
        public float AttackRange => heroClass == HeroClass.Archer ? 16f : heroClass == HeroClass.Mage ? 13f : 2.2f;
    }
}
